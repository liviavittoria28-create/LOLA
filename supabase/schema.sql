CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL DEFAULT 'Esther Lino',
  password_hash text NOT NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at text NOT NULL,
  created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL,
  phone_digits text NOT NULL,
  birth_date text,
  email text,
  notes text,
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_clients_name ON clients (lower(name));
CREATE INDEX IF NOT EXISTS idx_clients_phone ON clients (phone_digits);

CREATE TABLE IF NOT EXISTS anamneses (
  client_id bigint PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE,
  data text NOT NULL,
  consent integer NOT NULL DEFAULT 0,
  filled_at text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS procedures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text,
  price_cents integer NOT NULL,
  duration_min integer NOT NULL,
  active integer NOT NULL DEFAULT 1,
  sort integer NOT NULL DEFAULT 0,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS appointments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  date text NOT NULL,                 -- AAAA-MM-DD (horário de Brasília)
  start_at text NOT NULL,             -- AAAA-MM-DDTHH:MM:00-03:00
  end_at text NOT NULL,
  status text NOT NULL DEFAULT 'agendada',
  cancel_reason text,
  notes text,
  total_cents integer NOT NULL,
  duration_min integer NOT NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appt_date ON appointments (date);
CREATE INDEX IF NOT EXISTS idx_appt_client ON appointments (client_id);

CREATE TABLE IF NOT EXISTS appointment_procedures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  procedure_id bigint REFERENCES procedures(id),
  name text NOT NULL,                 -- valor e duração praticados no agendamento (RN08)
  price_cents integer NOT NULL,
  duration_min integer NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ap_appt ON appointment_procedures (appointment_id);

CREATE TABLE IF NOT EXISTS blocks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reason text NOT NULL,
  start_date text NOT NULL,
  end_date text NOT NULL,
  all_day integer NOT NULL DEFAULT 1,
  start_time text,
  end_time text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('in','out')),
  amount_cents integer NOT NULL CHECK (amount_cents > 0),
  date text NOT NULL,
  category text NOT NULL,
  method text,
  description text,
  client_id bigint REFERENCES clients(id),
  appointment_id bigint REFERENCES appointments(id) ON DELETE SET NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tx_date ON transactions (date);

CREATE TABLE IF NOT EXISTS wa_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
  phone text NOT NULL,
  jid text,
  status text NOT NULL,
  error text,
  reply text,
  reply_text text,
  sent_at text,
  replied_at text
);

-- sessão do WhatsApp conectado (para não precisar conectar de novo quando o servidor reinicia)
CREATE TABLE IF NOT EXISTS wa_auth (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  unit text NOT NULL DEFAULT 'un',
  quantity double precision NOT NULL DEFAULT 0,
  min_quantity double precision NOT NULL DEFAULT 0,
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_moves (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id bigint NOT NULL REFERENCES stock_items(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('in','out')),
  quantity double precision NOT NULL CHECK (quantity > 0),
  date text NOT NULL,
  note text,
  created_at text NOT NULL
);

-- =====================================================================
-- Lola — estrutura SaaS (várias empresas no mesmo banco)
-- Tudo abaixo só ACRESCENTA tabelas e colunas: nenhum dado existente é apagado.
-- Os dados que já existiam (antes da Lola) são ligados à empresa nº 1 pelo próprio app, ao ligar.
-- =====================================================================
CREATE TABLE IF NOT EXISTS companies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  owner_name text,
  email text,
  phone text,
  city text,
  segment text,
  status text NOT NULL DEFAULT 'trial',   -- trial | active | suspended | canceled
  trial_ends_at text,                     -- AAAA-MM-DD: último dia do teste grátis
  paid_until text,                        -- AAAA-MM-DD: último dia já pago
  price_cents integer NOT NULL DEFAULT 4990,
  notes text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

-- histórico de pagamentos (lançados pelo painel do proprietário; preparado para gateways no futuro)
CREATE TABLE IF NOT EXISTS payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  amount_cents integer NOT NULL CHECK (amount_cents > 0),
  paid_at text NOT NULL,                  -- AAAA-MM-DD
  method text,
  period_start text,
  period_end text,
  provider text NOT NULL DEFAULT 'manual', -- manual | (futuro: mercadopago, asaas, stripe…)
  provider_ref text,
  note text,
  created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payments_company ON payments (company_id);

CREATE TABLE IF NOT EXISTS password_resets (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at text NOT NULL,
  used_at text,
  created_at text NOT NULL
);

-- ajustes e sessão do WhatsApp, agora por empresa (as tabelas antigas "settings" e "wa_auth" ficam preservadas)
CREATE TABLE IF NOT EXISTS company_settings (
  company_id bigint NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  key text NOT NULL,
  value text NOT NULL,
  PRIMARY KEY (company_id, key)
);
CREATE TABLE IF NOT EXISTS wa_sessions (
  company_id bigint NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  key text NOT NULL,
  value text NOT NULL,
  PRIMARY KEY (company_id, key)
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS company_id bigint REFERENCES companies(id);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'owner';      -- owner | platform
ALTER TABLE users ADD COLUMN IF NOT EXISTS env_managed integer NOT NULL DEFAULT 0;  -- acesso definido por variáveis do servidor
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at text;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['clients','procedures','appointments','blocks','transactions','wa_messages','stock_items']
  LOOP
    EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS company_id bigint REFERENCES companies(id)', t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (company_id)', 'idx_' || t || '_company', t);
  END LOOP;
END $$;
CREATE INDEX IF NOT EXISTS idx_appt_company_date ON appointments (company_id, date);
CREATE INDEX IF NOT EXISTS idx_tx_company_date ON transactions (company_id, date);
CREATE INDEX IF NOT EXISTS idx_users_company ON users (company_id);

