-- SEGURANÇA (LGPD): o Supabase publica as tabelas numa API pública.
-- Com RLS ligado e sem nenhuma política, NINGUÉM acessa pela API pública
-- (nem com a chave "anon"). Só o servidor do app, pela conexão direta, lê e grava.
-- =====================================================================
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','sessions','settings','clients','anamneses','procedures','appointments',
    'appointment_procedures','blocks','transactions','wa_messages','wa_auth','stock_items','stock_moves',
    'companies','payments','password_resets','company_settings','wa_sessions']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE %I FROM anon, authenticated', t);
    END IF;
  END LOOP;
END $$;
